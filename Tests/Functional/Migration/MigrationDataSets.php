<?php

declare(strict_types=1);

namespace T3thi\StructureLayer\Tests\Functional\Migration;

use Psr\Http\Message\ResponseInterface;
use TYPO3\TestingFramework\Core\Functional\Framework\Frontend\ResponseContent;

/**
 * Data sets of the migration test (plan Phase 4), shared with the baseline recorder in
 * Build/baseline/: that one renders them on an unpatched Core without this extension (the
 * "before"), MigrationTest renders them after the migration (the "after").
 *
 * - RegularLocalize, RegularFreeMode: Core's DataScenarios import fixtures (Core 0a835c80f63),
 *   each with a strict, a fallback and a free site configuration.
 * - Visibility: hidden default records and translations, an expired default page, Free Mode.
 * - TranslationHandling: generated by the baseline recorder like the t3thi translation_handling
 *   extension does it (fallback/strict/free sites with free/connected/mixed pages, no FAL).
 */
final class MigrationDataSets
{
    public const string BASE = 'https://website.local/';

    /**
     * @return array<string, array{csv: string, sites: array<string, array<string, mixed>>, pages: array<string, list<int>>}>
     */
    public static function all(): array
    {
        $dataSets = [];
        foreach (['RegularLocalize' => [1, 88, 89, 90], 'RegularFreeMode' => [1, 88, 89, 90], 'Visibility' => [1, 10, 20, 30, 40]] as $name => $pages) {
            foreach (['strict', 'fallback', 'free'] as $fallbackType) {
                $dataSets[$name . '-' . $fallbackType] = [
                    'csv' => self::fixturePath($name . '.csv'),
                    'sites' => ['website' => self::siteConfiguration(1, self::BASE, $fallbackType)],
                    'pages' => ['website' => $pages],
                ];
            }
        }
        $generated = self::fixturePath('TranslationHandling.json');
        if (is_file($generated)) {
            $definition = json_decode((string)file_get_contents($generated), true, 512, JSON_THROW_ON_ERROR);
            $dataSets['TranslationHandling'] = [
                'csv' => self::fixturePath('TranslationHandling.csv'),
                'sites' => $definition['sites'],
                'pages' => $definition['pages'],
            ];
        }
        return $dataSets;
    }

    /**
     * Core's DataScenarios languages (EN default, DA → EN, DE → DA, EN), classic configuration.
     *
     * @return array<string, mixed>
     */
    public static function siteConfiguration(int $rootPageId, string $base, string $fallbackType): array
    {
        return [
            'rootPageId' => $rootPageId,
            'base' => $base,
            'languages' => [
                ['languageId' => 0, 'title' => 'English', 'enabled' => true, 'base' => '/', 'locale' => 'en_US.UTF-8', 'flag' => 'us'],
                ['languageId' => 1, 'title' => 'Dansk', 'enabled' => true, 'base' => '/da/', 'locale' => 'da_DK.UTF-8', 'flag' => 'dk', 'fallbackType' => $fallbackType, 'fallbacks' => '0'],
                ['languageId' => 2, 'title' => 'Deutsch', 'enabled' => true, 'base' => '/de/', 'locale' => 'de_DE.UTF-8', 'flag' => 'de', 'fallbackType' => $fallbackType, 'fallbacks' => '1,0'],
            ],
        ];
    }

    /**
     * Every page of every site in every language of the classic configuration. The old default
     * language keeps its base, so the same URLs address the same content after the migration.
     *
     * @param array{sites: array<string, array<string, mixed>>, pages: array<string, list<int>>} $dataSet
     * @return array<string, string> request key => URL
     */
    public static function urls(array $dataSet): array
    {
        $urls = [];
        foreach ($dataSet['sites'] as $identifier => $site) {
            foreach ($site['languages'] as $language) {
                foreach ($dataSet['pages'][$identifier] as $pageId) {
                    $key = $identifier . ' ' . $language['title'] . ' page ' . $pageId;
                    $urls[$key] = rtrim((string)$site['base'], '/') . '/' . ltrim((string)$language['base'], '/') . '?id=' . $pageId;
                }
            }
        }
        return $urls;
    }

    /**
     * What a visitor sees: status, page, content headers in order, menu. No uids: content uids
     * change for the old default language (it is a translation now).
     *
     * @return array{status: int, page?: int, title?: string, content?: list<string>, menu?: string}
     */
    public static function signature(ResponseInterface $response): array
    {
        if ($response->getStatusCode() !== 200) {
            return ['status' => $response->getStatusCode()];
        }
        $content = ResponseContent::fromString((string)$response->getBody());
        $headers = [];
        foreach ($content->getSection('Default')->getRecords() as $identifier => $record) {
            if (str_starts_with((string)$identifier, 'tt_content:')) {
                $headers[] = (string)($record['header'] ?? '');
            }
        }
        return [
            'status' => 200,
            'page' => (int)$content->getScopePath('page/uid'),
            'title' => (string)$content->getScopePath('page/title'),
            'content' => $headers,
            'menu' => (string)$content->getScopePath('menu'),
        ];
    }

    public static function fixturePath(string $fileName): string
    {
        return __DIR__ . '/Fixtures/' . $fileName;
    }

    public static function baselinePath(string $dataSetName): string
    {
        return self::fixturePath('Baseline/' . $dataSetName . '.json');
    }
}
